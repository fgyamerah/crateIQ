pytestmark = pytest.mark.skipif(shutil.which("ffmpeg") is None, reason="ffmpeg not available")


def _make_audio(path: Path, fmt: str = "mp3") -> None:
    codec = ["-c:a", "libmp3lame", "-b:a", "32k"] if fmt == "mp3" else ["-c:a", "flac"]
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i", "anullsrc=r=44100:cl=mono", "-t", "1", *codec, str(path)],
        check=True,
    )


def _write_tags(path: Path, **tags: str) -> None:
    from mutagen import File as MFile
    audio = MFile(str(path), easy=True)
    for key, value in tags.items():
        if value:
            audio[key] = [value]
    audio.save()


def _read_tags(path: Path) -> dict[str, str]:
    from mutagen import File as MFile
    audio = MFile(str(path), easy=True)
    get = lambda k: (audio.get(k) or [""])[0]
    return {k: get(k) for k in ("artist", "title", "album", "genre", "composer")}


@pytest.fixture()
def env(tmp_path, monkeypatch):
    root = tmp_path / "library_root"
    (root / "library").mkdir(parents=True)
    monkeypatch.setenv("CRATEIQ_LIBRARY_ROOT", str(root))
    monkeypatch.setattr(backend_db, "JOBS_DB_PATH", tmp_path / "jobs.db")
    backend_db.init_db()
    monkeypatch.setattr(svc, "TAG_WRITE_BACKUP_DIR", tmp_path / "tag_write_backups")

    db_path = root / "logs" / "processed.db"
    db_path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(db_path)
    conn.execute(
        "CREATE TABLE tracks (id INTEGER PRIMARY KEY AUTOINCREMENT, filepath TEXT NOT NULL UNIQUE, "
        "filename TEXT NOT NULL, artist TEXT, title TEXT, album TEXT, genre TEXT)"
    )
    conn.commit()
    conn.close()
    return root


def _insert_track(root: Path, *, filepath: Path, artist=None, title=None, album=None, genre=None) -> int:
    with sqlite3.connect(root / "logs" / "processed.db") as conn:
        cursor = conn.execute(
            "INSERT INTO tracks (filepath, filename, artist, title, album, genre) VALUES (?, ?, ?, ?, ?, ?)",
            (str(filepath), filepath.name, artist, title, album, genre),
        )
        return cursor.lastrowid


def test_build_plan_computes_exact_diff_and_is_side_effect_free(env):
    root = env
    path = root / "library" / "track.mp3"
    _make_audio(path)
    _write_tags(path, artist="Old Artist", title="Same Title", composer="Keep Me")
    track_id = _insert_track(root, filepath=path, artist="New Artist", title="Same Title", genre="House")

    original_bytes = path.read_bytes()
    plan = svc.build_plan([track_id])

    item = plan["items"][0]
    assert item["blocked"] is False
    fields = {f["field"]: f for f in item["fields"]}
    assert fields["artist"] == {"field": "artist", "current_file_value": "Old Artist", "approved_value": "New Artist", "action": "REPLACE"}
    assert fields["genre"] == {"field": "genre", "current_file_value": None, "approved_value": "House", "action": "ADD"}
    assert "title" not in fields, "identical value must never appear as a planned change"
    assert plan["additions"] == 1 and plan["replacements"] == 1
    assert path.read_bytes() == original_bytes, "preview must never touch the file"


def test_build_plan_expected_mtime_ns_is_a_string(env):
    """
    Regression: nanosecond epoch timestamps exceed Number.MAX_SAFE_INTEGER,
    so a JS client that round-trips expected_mtime_ns as a JSON *number*
    silently corrupts it, permanently failing apply_plan's staleness check
    for every real browser-driven write. It must be serialized as a string.
    """
    root = env
    path = root / "library" / "track.mp3"
    _make_audio(path)
    track_id = _insert_track(root, filepath=path, artist="New Artist")

    item = svc.build_plan([track_id])["items"][0]

    assert isinstance(item["expected_mtime_ns"], str)
    assert int(item["expected_mtime_ns"]) == path.stat().st_mtime_ns


