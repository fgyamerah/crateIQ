def test_build_plan_blocks_unsupported_format_and_missing_file(env):
    root = env
    wav_path = root / "library" / "track.wav"
    wav_path.write_bytes(b"not-really-audio-but-unsupported-anyway")
    wav_id = _insert_track(root, filepath=wav_path, artist="X")

    missing_path = root / "library" / "gone.mp3"
    missing_id = _insert_track(root, filepath=missing_path, artist="X")

    plan = svc.build_plan([wav_id, missing_id])
    by_id = {item["track_id"]: item for item in plan["items"]}
    assert by_id[wav_id]["blocked"] is True and "WAV" in by_id[wav_id]["blocker"]
    assert by_id[missing_id]["blocked"] is True and "no longer exists" in by_id[missing_id]["blocker"]
    assert plan["blocked_count"] == 2


