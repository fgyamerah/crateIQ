def test_restore_reverts_file_to_byte_identical_backup(env):
    root = env
    path = root / "library" / "track.mp3"
    _make_audio(path)
    _write_tags(path, artist="Original Artist", title="Original Title")
    original_bytes = path.read_bytes()
    track_id = _insert_track(root, filepath=path, artist="Changed Artist", title="Original Title")

    plan = svc.build_plan([track_id])
    item = plan["items"][0]
    expected = {track_id: {"expected_size": item["expected_size"], "expected_mtime_ns": item["expected_mtime_ns"]}}
    result = svc.apply_plan([track_id], expected, confirm=True)
    assert result["applied"] == 1
    assert path.read_bytes() != original_bytes, "sanity: the write actually changed the file"

    restore_result = svc.restore_file(result["operation_id"], track_id, confirm=True)

    assert restore_result["restored"] is True and restore_result["verified"] is True
    assert path.read_bytes() == original_bytes, "restored file must be byte-identical to the pre-write original"
    operation = svc.get_operation(result["operation_id"])
    assert operation["status"] == "restored"


