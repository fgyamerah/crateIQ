def test_apply_writes_only_approved_fields_preserves_unrelated_tags_and_audio(env):
    root = env
    path = root / "library" / "track.mp3"
    _make_audio(path)
    _write_tags(path, artist="Old Artist", title="Keep This Title", composer="Untouched Composer")
    track_id = _insert_track(root, filepath=path, artist="New Artist", title="Keep This Title", genre="Afro House")

    plan = svc.build_plan([track_id])
    item = plan["items"][0]
    expected = {track_id: {"expected_size": item["expected_size"], "expected_mtime_ns": item["expected_mtime_ns"]}}
    original_backup_source_bytes = path.read_bytes()

    result = svc.apply_plan([track_id], expected, confirm=True)

    assert result["status"] == "completed"
    assert result["applied"] == 1 and result["failed"] == 0
    tags = _read_tags(path)
    assert tags["artist"] == "New Artist"
    assert tags["genre"] == "Afro House"
    assert tags["title"] == "Keep This Title", "field with no diff must be left alone"
    assert tags["composer"] == "Untouched Composer", "unrelated tag must survive a write-back"

    from mutagen import File as MFile
    assert MFile(str(path)).info.length == pytest.approx(1.0, abs=0.2), "audio stream itself must be unaffected"

    operation = svc.get_operation(result["operation_id"])
    assert operation["status"] == "completed"
    manifest = operation["backup_manifest"][0]
    backup_path = svc.TAG_WRITE_BACKUP_DIR / result["operation_id"] / manifest["backup_filename"]
    assert backup_path.is_file()
    assert backup_path.read_bytes() == original_backup_source_bytes, "backup must be byte-for-byte the pre-write file"
    assert svc._sha256(backup_path) == manifest["original_sha256"]


def test_apply_blocks_stale_file_changed_since_preview(env):
    root = env
    path = root / "library" / "track.mp3"
    _make_audio(path)
    _write_tags(path, artist="Old Artist")
    track_id = _insert_track(root, filepath=path, artist="New Artist")

    plan = svc.build_plan([track_id])
    item = plan["items"][0]
    stale_expected = {track_id: {"expected_size": item["expected_size"] + 999, "expected_mtime_ns": item["expected_mtime_ns"]}}

    result = svc.apply_plan([track_id], stale_expected, confirm=True)

    assert result["failed"] == 1 and result["applied"] == 0
    assert "stale" in result["results"][0]["reason"].lower()
    assert _read_tags(path)["artist"] == "Old Artist", "a stale-blocked file must never be written"
    operation = svc.get_operation(result["operation_id"])
    assert operation["backup_manifest"] == [], "no backup should be created for a file blocked as stale"


