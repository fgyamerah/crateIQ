"""
Targeted tests for backend.app.services.tag_write_service (Cycle 7:
controlled metadata write-back).

These tests mutate REAL disposable audio fixtures generated by ffmpeg --
never anything under /home/paak/Music/crateiq-test-library. Every fixture
lives under pytest's tmp_path and is discarded after the test.

TAG_WRITE_BACKUP_DIR and JOBS_DB_PATH are monkeypatched per test so no test
run ever writes into this repo's real backend/data/ directory.
"""
